/**
 * Per-agent toggles for SSH deploy: disable presets on the remote DSH profile
 * and apply PATH-friendly command overrides for enabled agents.
 */

import type { RemoteAgentDeploySelection } from './types.ts'

export type RemoteDeployAgentKey = keyof RemoteAgentDeploySelection

export type RemoteDeployAgentSpec = {
  readonly key: RemoteDeployAgentKey
  readonly presetId: string
  readonly label: string
  readonly command: string
}

/** Preset ids installed by the default GitHub ThreadHarbor bundle. */
export const REMOTE_DEPLOY_AGENT_SPECS: readonly RemoteDeployAgentSpec[] = [
  { key: 'codex', presetId: 'acp-codex', label: 'Codex', command: 'codex-acp' },
  { key: 'claude', presetId: 'acp-claude', label: 'Claude', command: 'claude-agent-acp' },
  { key: 'grok', presetId: 'acp-grok', label: 'Grok', command: 'grok' },
  { key: 'cursor', presetId: 'acp-cursor', label: 'Cursor', command: 'cursor-agent' },
]

const ALL_KEYS = REMOTE_DEPLOY_AGENT_SPECS.map(spec => spec.key)

function isAgentKey(value: string): value is RemoteDeployAgentKey {
  return (ALL_KEYS as readonly string[]).includes(value)
}

/** Resolve UI / API toggles into enabled preset ids (default: all on). */
export function enabledRemotePresetIds(selection?: RemoteAgentDeploySelection): readonly string[] {
  const enabled: string[] = []
  for (const spec of REMOTE_DEPLOY_AGENT_SPECS) {
    const on = selection === undefined ? true : selection[spec.key] !== false
    if (on) enabled.push(spec.presetId)
  }
  return enabled
}

export function parseRemoteAgentSelection(value: unknown): RemoteAgentDeploySelection | undefined {
  if (value === undefined || value === null) return undefined
  if (!Array.isArray(value)) {
    if (typeof value !== 'object') throw new Error('remoteAgents 必须是对象或 preset id 数组')
    const record = value as Record<string, unknown>
    const out: Partial<Record<RemoteDeployAgentKey, boolean>> = {}
    for (const spec of REMOTE_DEPLOY_AGENT_SPECS) {
      const raw = record[spec.key]
      if (raw === undefined) continue
      if (typeof raw !== 'boolean') throw new Error(`remoteAgents.${spec.key} 必须是布尔值`)
      out[spec.key] = raw
    }
    return out
  }
  const toggles: Partial<Record<RemoteDeployAgentKey, boolean>> = {}
  for (const spec of REMOTE_DEPLOY_AGENT_SPECS) toggles[spec.key] = false
  for (const item of value) {
    if (typeof item !== 'string') continue
    const trimmed = item.trim()
    const byPreset = REMOTE_DEPLOY_AGENT_SPECS.find(spec => spec.presetId === trimmed)
    if (byPreset !== undefined) {
      toggles[byPreset.key] = true
      continue
    }
    if (isAgentKey(trimmed)) toggles[trimmed] = true
  }
  return toggles
}

function bindingId(presetId: string): string {
  return `${presetId}-binding`
}

/** Cordis patch overlay written under the remote profile and passed to `dsh web --patch`. */
export function buildRemoteAgentsPatchYaml(selection?: RemoteAgentDeploySelection): string {
  const enabled = new Set(enabledRemotePresetIds(selection))
  const lines: string[] = [
    '# Generated by ThreadHarbor SSH deploy — remote agent toggles.',
    '- insert:',
  ]
  for (const spec of REMOTE_DEPLOY_AGENT_SPECS) {
    if (!enabled.has(spec.presetId)) {
      lines.push(`    - id: ${spec.presetId}`)
      lines.push('      disabled: true')
      continue
    }
    lines.push(`    - id: ${spec.presetId}`)
    lines.push('      config:')
    lines.push('        plugins:')
    lines.push(`          - id: ${bindingId(spec.presetId)}`)
    lines.push('            config:')
    lines.push(`              command: ${spec.command}`)
    lines.push('              hideFromRoster: true')
  }
  return `${lines.join('\n')}\n`
}
